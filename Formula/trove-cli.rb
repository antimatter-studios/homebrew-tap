    end
    on_intel do
      url "https://github.com/antimatter-studios/trove/releases/download/v#{version}/trove-#{version}-darwin-x86_64.tar.gz"
      sha256 "b3d343292d7ab6c3619831f00ed915c7b52bc2368e2885ce072fe2e28bd381a6"
    end
